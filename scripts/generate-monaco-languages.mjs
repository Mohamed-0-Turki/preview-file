/**
 * Regenerate `src/utils/monaco-languages.ts` from Monaco Editor's own language
 * registry (`monaco.languages.getLanguages()`), keeping routing in sync with
 * every language Monaco ships — no hand-maintained language list.
 *
 * Usage (a browser + playwright-core are required; the library itself never
 * depends on either):
 *
 *   node scripts/generate-monaco-languages.mjs --playwright-dir <dir>
 *
 * `--playwright-dir` must point at a folder whose `node_modules` contains
 * `playwright-core` (e.g. a throwaway harness). The script boots a headless
 * Chromium, loads the pinned AMD build from the CDN, reads the live registry
 * and writes the TypeScript index. Rerun it whenever the pinned Monaco version
 * in `src/monaco.ts` changes.
 *
 * The generated file is committed. The build/typecheck/lint do not (and must
 * not) run this script — consumers never need a browser.
 */
import { createServer } from 'node:http'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { writeFile } from 'node:fs/promises'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const OUT_FILE = path.join(ROOT, 'src', 'utils', 'monaco-languages.ts')

/* Keep in sync with src/monaco.ts (MONACO_VERSION). */
const MONACO_VERSION = '0.56.0'
const CDN_BASE = `https://cdn.jsdelivr.net/npm/monaco-editor@${MONACO_VERSION}/min`

function playwrightDirFromArgs(argv) {
  const flagIndex = argv.indexOf('--playwright-dir')
  if (flagIndex === -1 || !argv[flagIndex + 1]) {
    throw new Error('Missing --playwright-dir <dir> (folder with playwright-core in node_modules)')
  }
  return argv[flagIndex + 1]
}

async function dumpLanguages(playwrightDir) {
  const require = createRequire(path.join(playwrightDir, 'noop.cjs'))
  const { chromium } = require('playwright-core')

  const server = createServer((_req, res) => {
    res.setHeader('content-type', 'text/html')
    res.end(
      `<!doctype html><html><body><script>
        window.__dump = new Promise((resolve, reject) => {
          var s = document.createElement('script');
          s.src = ${JSON.stringify(`${CDN_BASE}/vs/loader.js`)};
          s.onload = function () {
            require.config({ baseUrl: ${JSON.stringify(CDN_BASE)}, paths: { vs: ${JSON.stringify(`${CDN_BASE}/vs`)} } });
            require(['vs/editor/editor.main'], function () {
              resolve(window.monaco.languages.getLanguages());
            }, reject);
          };
          s.onerror = reject;
          document.head.appendChild(s);
        });
      </script></body></html>`
    )
  })
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve))
  const port = server.address().port

  const browser = await chromium.launch({ args: ['--no-sandbox'] })
  try {
    const page = await browser.newPage()
    await page.goto(`http://127.0.0.1:${port}/`, { waitUntil: 'load' })
    const languages = await page.evaluate(() => window.__dump)
    return languages
  } finally {
    await browser.close()
    server.close()
  }
}

function stripDot(value) {
  return value.startsWith('.') ? value.slice(1) : value
}

function serialize(record) {
  return Object.entries(record)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
    .join('\n')
}

function buildIndex(languages) {
  const extensionToLanguage = {}
  const filenameToLanguage = {}
  const languageToMimetype = {}
  const mimeTypes = new Set()

  for (const language of languages) {
    const id = language.id
    for (const extension of language.extensions ?? []) {
      const key = stripDot(extension).toLowerCase()
      if (key && !(key in extensionToLanguage)) extensionToLanguage[key] = id
    }
    for (const filename of language.filenames ?? []) {
      const key = filename.toLowerCase()
      if (key && !(key in filenameToLanguage)) filenameToLanguage[key] = id
    }
    const mime = (language.mimetypes ?? [])[0]
    if (mime && !(id in languageToMimetype)) languageToMimetype[id] = mime
    for (const mimetype of language.mimetypes ?? []) {
      if (mimetype) mimeTypes.add(mimetype)
    }
  }

  return {
    total: languages.length,
    extensionToLanguage,
    filenameToLanguage,
    languageToMimetype,
    mimeTypes: [...mimeTypes].sort(),
  }
}

function renderTs(index) {
  const now = new Date().toISOString().slice(0, 10)
  return `/* <auto-generated>
 * Generated from Monaco Editor ${MONACO_VERSION}'s own language registry by
 * scripts/generate-monaco-languages.mjs on ${now} — do not edit by hand.
 *
 * Routing-only index: it answers one question at preview time, before Monaco
 * has been fetched ("is this file a language Monaco knows?"). The actual
 * language resolution at render time always consults the live registry
 * (monaco.languages.getLanguages()), so this table can never drift out of sync
 * with what Monaco supports — it is generated from exactly that source.
 *
 * Regenerate with:
 *   node scripts/generate-monaco-languages.mjs --playwright-dir <dir>
 */
export const MONACO_LANGUAGE_TOTAL = ${index.total}

/** Lowercased, dot-less extension → Monaco language id. */
export const EXTENSION_TO_LANGUAGE: Readonly<Record<string, string>> = {
${serialize(index.extensionToLanguage)}
}

/** Lowercased file name (e.g. \`dockerfile\`, \`gemfile\`, \`tsconfig.json\`) → language id. */
export const FILENAME_TO_LANGUAGE: Readonly<Record<string, string>> = {
${serialize(index.filenameToLanguage)}
}

/** Language id → its first declared MIME type, used for routing. */
export const LANGUAGE_TO_MIMETYPE: Readonly<Record<string, string>> = {
${serialize(index.languageToMimetype)}
}

/** Every MIME type Monaco languages declare for themselves. */
export const MONACO_MIME_TYPES: readonly string[] = [
${index.mimeTypes.map((m) => `  ${JSON.stringify(m)},`).join('\n')}
]
`
}

const playwrightDir = playwrightDirFromArgs(process.argv)
const languages = await dumpLanguages(playwrightDir)
const index = buildIndex(languages)
await writeFile(OUT_FILE, renderTs(index), 'utf8')
console.log(`Wrote ${path.relative(ROOT, OUT_FILE)} (${index.total} languages, ${index.extensionToLanguage.length} extensions, ${index.filenameToLanguage.length} filenames, ${index.mimeTypes.length} MIME types)`)